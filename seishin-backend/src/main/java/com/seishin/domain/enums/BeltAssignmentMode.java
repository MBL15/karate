package com.seishin.domain.enums;

public enum BeltAssignmentMode {
    /** Пояс выдаёт только тренер; автоматический прогресс не показывается. */
    MANUAL,
    /** Прогресс — доля посещений на текущем поясе до следующего уровня. */
    ATTENDANCE,
    /** Прогресс — балл готовности: посещаемость, значки, рекомендация тренера. */
    READINESS
}
